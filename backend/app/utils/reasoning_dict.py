def build_guidance_block() -> str:
    """返回注入 system_prompt 的判定字典文本块。"""
    parts = [
        "【青囊判定字典 K-REASON】",
        "以下为系统预计算的判定语义，直接采信、不要自己重新卡阈值：",
        "",
        "── 方向判定（A）──",
        *[f"· {r}" for r in DIRECTION_RULES],
        "",
        "── 五形状态 → 生活动作（B，可查出处）──",
    ]
    for item in WUXING_TO_LIFE:
        parts.append(f"· {item['state']}：{item['life']}")
        parts.append(f"    动作：{'、'.join(item['actions'])}")
        parts.append(f"    出处：{item['source']}")
    parts += [
        "",
        "── 失效边界（C）── 命中以下情况，必须克制，不得用范式硬套：",
        *[f"· {b}" for b in FAILURE_BOUNDARIES],
        "",
    ]
    return "\n".join(parts)