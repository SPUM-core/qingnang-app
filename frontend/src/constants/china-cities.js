export function getCitiesByProvince(provinceCode) {
  return CHINA_CITIES[provinceCode] || []
}

/**
 * 根据城市名查找经度（用于真太阳时修正）
 */
export function findCityLng(cityName) {
  for (const [provCode, cities] of Object.entries(CHINA_CITIES)) {
    const match = cities.find(c => c.name === cityName)
    if (match) return match.lng
  }
  return null
}
